"""同じJSON Schemaから、依存のないTypeScriptの型宣言だけを生成する。"""

from __future__ import annotations

import json

from .specification import OPERATIONS


def _literal(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def schema_type(schema: dict) -> str:
    unsupported = {"oneOf", "not", "if", "then", "else", "prefixItems", "patternProperties",
                   "unevaluatedProperties", "dependentSchemas"}
    if unsupported.intersection(schema):
        raise ValueError("Unsupported structural keyword in TypeScript export")
    if "$ref" in schema:
        prefix = "#/$defs/"
        if not schema["$ref"].startswith(prefix):
            raise ValueError("Only local schema references are supported")
        return schema["$ref"][len(prefix):]
    if "const" in schema:
        return _literal(schema["const"])
    if "enum" in schema:
        return " | ".join(_literal(item) for item in schema["enum"])
    if "anyOf" in schema:
        return " | ".join("(" + schema_type(item) + ")" for item in schema["anyOf"])
    if "allOf" in schema:
        return " & ".join("(" + schema_type(item) + ")" for item in schema["allOf"])
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind == "boolean":
        return "boolean"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "string":
        return "Blob" if schema.get("format") == "binary" else "string"
    if kind == "array":
        return "Array<" + schema_type(schema["items"]) + ">"
    if kind == "object":
        properties = schema.get("properties", {})
        required = set(schema.get("required", []))
        fields = []
        for key, value in properties.items():
            fields.append(f"  {_literal(key)}{'' if key in required else '?'}: {schema_type(value)};")
        result = "{\n" + "\n".join(fields) + "\n}" if fields else "Record<string, never>"
        additional = schema.get("additionalProperties", True)
        if additional is True:
            index = "Record<string, unknown>"
        elif isinstance(additional, dict):
            index = "Record<string, " + schema_type(additional) + ">"
        else:
            index = None
        return "(" + result + " & " + index + ")" if fields and index else index or result
    raise ValueError("Unsupported schema construct in TypeScript export")


def typescript_declarations(bundle: dict) -> str:
    lines = [
        "// Generated by scripts/build_api_contract.py. Do not edit.",
        "// Runtime validation remains on the backend; these are compile-time declarations.",
        "// API schema_version values and this contract's revision are separate.",
        "",
    ]
    for name, schema in bundle["$defs"].items():
        lines.extend(["export type " + name + " = " + schema_type(schema) + ";", ""])
    lines.extend([
        'export type EvaluationCondition = Evaluation["conditions"][number];',
        'export type Judgment = Evaluation["status"];',
        'export type CourseResult = TranscriptCourse["status"];',
        'export type SlotRecommendationStatus = SlotRecommendationsResponse["status"];',
        'export type SearchRecommendationStatus = RecommendationSearchResponse["status"];',
        "",
        "// Values before FormData serialization. Files are File or Blob; numbers become strings.",
        "export interface ApiOperations {",
    ])
    for operation in OPERATIONS:
        key = operation["method"].upper() + " " + operation["path"]
        request = operation["request"] or "undefined"
        response = operation["response"] or "never"
        headers = "; headers: " + operation["headers"] if operation.get("headers") else ""
        lines.append(f"  {_literal(key)}: {{ request: {request}; response: {response}; error: ErrorResponse{headers} }};")
    lines.extend(["}", "", "export type ApiOperation = keyof ApiOperations;", ""])
    return "\n".join(lines)
